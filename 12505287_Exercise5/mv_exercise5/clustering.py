def filter_clusters_by_dimension(labels, k_std = 0.7):
    '''
    We want to perform the algorithm on real objects.
    We try to remove random clusters generated by noise or points from the plane for instance.
    '''
    unique_labels = np.unique(labels)
    cluster_sizes = np.array([np.sum(labels == id) for id in unique_labels if id >= 0])

    median_size = np.median(cluster_sizes)
    std_size = np.std(cluster_sizes)

    threshold_size = median_size - k_std * std_size

    filtered_labels = labels.copy()
    for id in unique_labels:
        if id < 0:
            continue
        if np.sum(labels == id) < threshold_size:
            print(f"Cluster {id} doesn't has enough points to be considered a real object")
            filtered_labels[labels == id] = -1

    return filtered_labels

